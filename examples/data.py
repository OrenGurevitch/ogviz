"""Invented groups, so every example runs on a clean clone and shows nobody's data.

Fixed seeds: the gallery is regenerated by CI and by `just figures`, and an image that changes on
every run is a diff nobody can read. The shapes are chosen to exercise the awkward cases — a
skewed group, a small group beside a large one, values that need three decimals, values that need
a thousands separator.

The PARAMETERS are round and arbitrary on purpose. Drawing a synthetic sample is not enough: an
earlier version of this file seeded its generators with a real study's group means and real group
sizes, which puts that study's unpublished result in a public repository however synthetic the
individual points are. Nothing here should be recoverable as anyone's finding — if a number looks
plausibly like a measurement, that is the bug.
"""

