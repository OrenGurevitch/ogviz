def coupled_variables(seed: int = 8) -> dict[str, dict[str, np.ndarray]]:
    """Three variables on two groups, made to disagree pooled versus within.

    The groups sit apart on every axis while barely trending inside themselves, which is the
    arrangement a coupling figure exists to expose: pool them and the correlation is strong, look
    within either one and it nearly vanishes. Made-up numbers on made-up scales.
    """
    rng = np.random.default_rng(seed)
    out: dict[str, dict[str, np.ndarray]] = {}
    for name, size, offset in (("control", 40, 0.0), ("treated", 60, 2.0)):
        shared = rng.normal(0.0, 1.0, size)
        out[name] = {
            "marker": offset + 0.35 * shared + rng.normal(0.0, 1.0, size),
            "mass": offset + 0.35 * shared + rng.normal(0.0, 1.0, size),
            "burden": offset + 0.35 * shared + rng.normal(0.0, 1.0, size),
        }
    return out


def _spearman(x: np.ndarray, y: np.ndarray) -> float:
    """Pearson on the ranks. Written out so the examples need no statistics dependency."""
    rank_x = np.argsort(np.argsort(x)).astype(float)
    rank_y = np.argsort(np.argsort(y)).astype(float)
    centred_x, centred_y = rank_x - rank_x.mean(), rank_y - rank_y.mean()
    denominator = np.sqrt((centred_x**2).sum() * (centred_y**2).sum())
    return float((centred_x * centred_y).sum() / denominator) if denominator else 0.0


def correlation_with_interval(
    x: np.ndarray, y: np.ndarray, *, draws: int = 2000, seed: int = 9
) -> tuple[float, tuple[float, float], float]:
    """A rank correlation, a percentile bootstrap interval, and a permutation p.

    Statistics belong to the caller — ogviz places marks at numbers, it does not produce them.
    This is here so the example is runnable, not because it is the estimator anyone should use.
    """
    rng = np.random.default_rng(seed)
    estimate = _spearman(x, y)
    indices = rng.integers(0, x.size, size=(draws, x.size))
    resampled = np.array([_spearman(x[take], y[take]) for take in indices])
    low, high = (float(v) for v in np.percentile(resampled, [2.5, 97.5]))
    shuffled = np.array([_spearman(x, rng.permutation(y)) for _ in range(draws)])
    p = float((np.count_nonzero(np.abs(shuffled) >= abs(estimate)) + 1) / (draws + 1))
    # The interval is widened to contain the estimate if it does not already, because `Estimate`
    # refuses a dot outside its own bar. That is a real thing a percentile bootstrap can do on a
    # skewed statistic, and widening HIDES it — so it is written down here rather than left as a
    # `min`/`max` a reader would copy without noticing. On this file's data it never fires; checked
    # across all six pairs the gallery draws, the reported interval is the percentile one unchanged.
    # A project doing this for real should let the disagreement surface instead of smoothing it.
    return estimate, (min(low, estimate), max(high, estimate)), p


