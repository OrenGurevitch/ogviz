def coupled_variables(seed: int = 8) -> dict[str, dict[str, np.ndarray]]:
    """Three variables on two groups, made to disagree pooled versus within.

    The groups sit apart on every axis while barely trending inside themselves, which is the
    arrangement a coupling figure exists to expose: pool them and the correlation is strong, look
    within either one and it nearly vanishes. Made-up numbers on made-up scales.
    """
    rng = np.random.default_rng(seed)
    out: dict[str, dict[str, np.ndarray]] = {}
    for name, size, offset in (("control", 40, 0.0), ("treated", 60, 2.0)):
        shared = rng.normal(0.0, 1.0, size)
        out[name] = {
            "marker": offset + 0.35 * shared + rng.normal(0.0, 1.0, size),
            "mass": offset + 0.35 * shared + rng.normal(0.0, 1.0, size),
            "burden": offset + 0.35 * shared + rng.normal(0.0, 1.0, size),
        }
    return out


def _spearman(x: np.ndarray, y: np.ndarray) -> float:
    """Pearson on the ranks. Written out so the examples need no statistics dependency."""
    rank_x = np.argsort(np.argsort(x)).astype(float)
    rank_y = np.argsort(np.argsort(y)).astype(float)
    centred_x, centred_y = rank_x - rank_x.mean(), rank_y - rank_y.mean()
    denominator = np.sqrt((centred_x**2).sum() * (centred_y**2).sum())
    return float((centred_x * centred_y).sum() / denominator) if denominator else 0.0


def correlation_with_interval(
    x: np.ndarray, y: np.ndarray, *, draws: int = 2000, seed: int = 9
) -> tuple[float, tuple[float, float], float]:
    """A rank correlation, a percentile bootstrap interval, and a permutation p.

    Statistics belong to the caller — ogviz places marks at numbers, it does not produce them.
    This is here so the example is runnable, not because it is the estimator anyone should use.
    """
    rng = np.random.default_rng(seed)
    estimate = _spearman(x, y)
    indices = rng.integers(0, x.size, size=(draws, x.size))
    resampled = np.array([_spearman(x[take], y[take]) for take in indices])
    low, high = (float(v) for v in np.percentile(resampled, [2.5, 97.5]))
    shuffled = np.array([_spearman(x, rng.permutation(y)) for _ in range(draws)])
    p = float((np.count_nonzero(np.abs(shuffled) >= abs(estimate)) + 1) / (draws + 1))
    return estimate, (min(low, estimate), max(high, estimate)), p


REGION_NAMES = ("Region A", "Region B", "Region C", "Region D")


def region_panels(seed: int = 11) -> dict[str, tuple[np.ndarray, np.ndarray, float]]:
    """Four regions measured in two groups, with a p for each — the one-panel-per-region case.

    The effects run from clear to absent on purpose. A grid where every panel tells the same story
    does not test anything: the interesting question is whether four panels drawn to one scale
    still let a reader see which region moved.
    """
    rng = np.random.default_rng(seed)
    separations = (-1.10, -0.72, -0.35, 0.04)
    p_values = (0.0004, 0.008, 0.06, 0.71)
    out: dict[str, tuple[np.ndarray, np.ndarray, float]] = {}
    for name, shift, p in zip(REGION_NAMES, separations, p_values, strict=True):
        out[name] = (
            rng.normal(0.0, 1.0, 38),
            rng.normal(shift, 1.05, 52),
            p,
        )
    return out


EFFORT_COST = (0.25, 0.35, 0.70, 1.30, 2.00, 2.60)


def effort_ladders(seed: int = 12) -> dict[str, tuple[np.ndarray, np.ndarray]]:
    """Score against cost for four systems, each measured at a few effort settings.

    Not a sampled curve — five or six measured points per system, which is why the marks matter as
    much as the line joining them.
    """
    rng = np.random.default_rng(seed)
    cost = np.array(EFFORT_COST)
    ladders = {
        "System A": (cost, np.array([56.1, 58.0, 61.3, 63.2, 64.8, 64.7])),
        "System B": (cost[2:], np.array([58.2, 61.4, 61.8, 63.1])),
        "System C": (cost[1:5], np.array([50.2, 55.2, 55.7, 57.6])),
        "Baseline": (cost, np.array([40.0, 44.0, 47.0, 49.0, 50.2, 50.5])),
    }
    return {name: (x, y + rng.normal(0.0, 0.05, y.size)) for name, (x, y) in ladders.items()}


NATIONS = ("Air Nomads", "Water Tribe", "Earth Kingdom", "Fire Nation")


def bending_by_nation(seed: int = 13) -> dict[str, tuple[np.ndarray, np.ndarray, float]]:
    """Novice against master benders in each of the four nations. Entirely invented.

    Four panels of the same comparison at different strengths, which is what a grid is for: the
    Air Nomads separate cleanly, the Fire Nation barely at all.
    """
    rng = np.random.default_rng(seed)
    separations = (1.35, 0.95, 0.55, 0.12)
    p_values = (0.0002, 0.006, 0.05, 0.68)
    return {
        nation: (
            rng.normal(0.0, 1.0, 36),
            rng.normal(shift, 1.05, 48),
            p,
        )
        for nation, shift, p in zip(NATIONS, separations, p_values, strict=True)
    }


