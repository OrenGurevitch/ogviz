def two_groups(seed: int = 0) -> dict[str, np.ndarray]:
    """A moderate separation with unequal n — the ordinary case."""
    rng = np.random.default_rng(seed)
    return {
        "control": rng.normal(0.0, 1.0, 40),
        "treated": rng.normal(-1.0, 1.2, 55),
    }


def concentration_ppm(seed: int = 5) -> dict[str, np.ndarray]:
    """Stored in ppm the way an instrument emits it, and read in ppb by everyone who uses it.

    This is the case display_scale exists for: without it the axis says "ppb" and carries
    -0.002, and a printed mean reads "-0.00".
    """
    rng = np.random.default_rng(seed)
    return {
        "control": rng.normal(2.0e-3, 0.5e-3, 40),
        "treated": rng.normal(3.5e-3, 0.6e-3, 55),
    }


def skewed_groups(seed: int = 1) -> dict[str, np.ndarray]:
    """One long tail, to show the violin doing something a box plot cannot."""
    rng = np.random.default_rng(seed)
    return {
        "control": rng.gamma(2.0, 0.6, 30) + 1.0,
        "treated": rng.gamma(6.0, 0.4, 44) + 1.0,
    }


def large_magnitudes(seed: int = 2) -> dict[str, np.ndarray]:
    """Values that need a thousands separator, like a relaxation time in milliseconds."""
    rng = np.random.default_rng(seed)
    return {"control": rng.normal(500, 40, 40), "treated": rng.normal(560, 45, 55)}


