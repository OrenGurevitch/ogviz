def paired_sensors(seed: int = 6) -> tuple[list[np.ndarray], list[np.ndarray]]:
    """The same quantity measured two ways per category — the split-violin case.

    Nearly identical on purpose: the point of a shared spine is that a pair which agrees LOOKS
    like it agrees, where side-by-side violins leave a gap the eye reads as a difference.
    """
    rng = np.random.default_rng(seed)
    centres = (700.0, 760.0, 690.0, 700.0, 755.0, 685.0)
    first = [rng.normal(c, 45, 220) for c in centres]
    second = [a + rng.normal(0.0, 3.0, a.size) for a in first]
    return first, second


